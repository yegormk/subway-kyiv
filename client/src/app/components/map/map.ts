  private initMap() {
    this.map = new maplibregl.Map({
      style: 'https://tiles.openfreemap.org/styles/liberty',
      center: [30.556059050602947, 50.43865448846939],
      zoom: 11,
      container: 'map',
    });

    this.map.on('load', () => {
      this.metroLines.forEach((line) => {
        const normalizedName = line.name.toLowerCase().replace(/\s+/g, '-');
        const sourceId = `${normalizedName}-source`;
        const layerId = `${normalizedName}-layer`;

        this.map.addSource(sourceId, {
          'type': 'geojson',
          'data': {
            'type': 'Feature',
            'properties': {},
            'geometry': {
              'type': 'LineString',
              'coordinates': line.coordinates
            }
          }
        });

        this.map.addLayer({
          'id': layerId,
          'type': 'line',
          'source': sourceId,
          'layout': {
            'line-join': 'round',
            'line-cap': 'round'
          },
          'paint': {
            'line-color': line.color,
            'line-width': 2
          }
        });

        this.stationsService.loadSubwayStations().subscribe((value: SubwayStation[]) => {
          value.forEach(station => {
            const el = document.createElement('div');
            el.className = 'marker';
            el.style.backgroundImage = `url('./assets/${ station.branch }_m.png')`;
            el.style.backgroundSize = 'contain';
            el.style.width = `20px`;
            el.style.height = `15px`;
            el.style.cursor = 'pointer';

            el.addEventListener('click', () => {
              this.dialog.open(StationInfo, {
                width: '550px',
                data: {
                  name: station.name,
                  description: station.description
                },
              });
            });

            new maplibregl.Marker({ element: el })
              .setLngLat(station.coordinates)
              .addTo(this.map);
          });
        });
      });
    });
  }
